export function lastSeasonOrder(teams: Team[]) {
  return [...teams]
    .sort((a, b) => {
      const rank = (team: Team) =>
        team.lastSeason.league === 'Premier League'
          ? team.lastSeason.position
          : 100 + team.lastSeason.position
      return rank(a) - rank(b)
    })
    .map((team) => team.id)
}

export const DEFAULT_ORDER = lastSeasonOrder(TEAMS)

export function crestUrl(code: string, size: 50 | 70 | 100 = 70) {
  return `https://resources.premierleague.com/premierleague/badges/${size}/${code}.png`
}

export function qualificationBand(position: number) {
  if (position <= 4) return 'ucl' as const
  if (position === 5) return 'uel' as const
  if (position === 6) return 'uecl' as const
  if (position >= 18) return 'rel' as const
  return 'mid' as const
}

export function ordinal(n: number) {
  const v = n % 100
  if (v >= 11 && v <= 13) return `${n}th`
  switch (n % 10) {
    case 1:
      return `${n}st`
    case 2:
      return `${n}nd`
    case 3:
      return `${n}rd`
    default:
      return `${n}th`
  }
}
